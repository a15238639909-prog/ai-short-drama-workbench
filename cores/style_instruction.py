def _notes():
    return json.loads(NOTES_FILE.read_text(encoding="utf-8"))


def styles():
    """有渲染要点的画风列表（顺序稳定）。"""
    return [k for k in _notes() if not k.startswith("_")]


def build(style, target="character"):
    """拼出某个画风、某种图的指令词。target: character | scene"""
    n = _notes().get(style)
    if not n:
        raise KeyError("画风「%s」没有渲染要点，去 presets/render_notes.json 里补" % style)
    t = TARGET[target]
    return TEMPLATE.format(
        obj="人物" if target == "character" else "场景",
        style=style, fields=t["fields"], section=t["section"],
        what=t["what"], why=t["why"],
        notes=n["char"] if target == "character" else n["scene"],
        kindname=KIND_NAME[n["kind"]], ban=TEXTURE_BAN[n["kind"]],
        rules="\n\n".join("%d、%s" % (i + 1, r) for i, r in enumerate(t["rules"])),
        styleline=(STYLE_LINE[n["kind"]]
                   .replace("<这个画风>", style.split("·")[-1])
                   .replace("<画法>", STYLE_OPENER.get(style, ""))),
        layout=t["layout"])

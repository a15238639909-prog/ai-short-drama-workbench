'use strict';
const assert = require('node:assert/strict');
const {project, harness, flush} = require('./test_settings_pov_owner_ui.js');

async function main(){
  const fresh=project('我','电影第三人称');
  fresh.settings.image_model='moss';fresh.settings.image_quality='2x';
  const old=project('我','电影第三人称');
  const projects={NEW:fresh,OLD:old},h=harness(projects),get=id=>h.document.getElementById(id);
  await h.render('NEW');
  assert.equal(get('psImageModel').value,'moss');
  assert.equal(get('psSceneImageModel').value,'moss');
  assert.equal(get('psImageQuality').value,'2x');
  assert.equal(get('psImageQualityWrap').hidden,false);
  get('psImageQuality').value='4k';await get('psImageQuality').onchange();await flush();
  assert.equal(projects.NEW.settings.image_quality,'4k');
  get('psImageModel').value='krea2';const first=get('psImageModel').onchange();
  assert.equal(get('psImageQuality').disabled,false);
  get('psSceneImageModel').value='krea2';const sceneChange=get('psSceneImageModel').onchange();
  assert.equal(get('psImageQuality').disabled,true);
  get('psImageModel').value='moss';const second=get('psImageModel').onchange();
  await Promise.all([first,sceneChange,second]);await flush();
  assert.equal(projects.NEW.settings.image_model,'moss');
  assert.equal(projects.NEW.settings.character_image_model,'moss');
  assert.equal(projects.NEW.settings.scene_image_model,'krea2');
  assert.equal(projects.NEW.settings.image_quality,'4k');
  assert.equal(get('psImageQuality').disabled,false);
  await h.save();
  let saved=h.settingPosts().at(-1).payload;
  assert.equal(saved.story_id,'NEW');assert.equal(saved.settings.image_model,'moss');assert.equal(saved.settings.image_quality,'4k');
  assert.equal(saved.settings.character_image_model,'moss');
  assert.equal(saved.settings.scene_image_model,'krea2');
  get('psImageModel').value='krea2';await get('psImageModel').onchange();
  get('psSceneImageModel').value='moss';await get('psSceneImageModel').onchange();await flush();
  await h.render('NEW');
  assert.equal(get('psImageModel').value,'krea2');
  assert.equal(get('psSceneImageModel').value,'moss');
  assert.equal(get('psImageQuality').disabled,false);
  await h.save();saved=h.settingPosts().at(-1).payload;
  assert.equal(saved.settings.character_image_model,'krea2');
  assert.equal(saved.settings.scene_image_model,'moss');
  await h.render('OLD');
  assert.equal(get('psImageModel').value,'krea2');
  assert.equal(get('psSceneImageModel').value,'krea2');
  assert.equal(get('psImageQualityWrap').hidden,true);
  assert.equal(projects.OLD.settings.image_model,undefined);
  await h.save();saved=h.settingPosts().at(-1).payload;
  assert.equal(saved.story_id,'OLD');assert.equal(saved.settings.image_model,'krea2');
  assert.equal(projects.NEW.settings.image_model,'krea2');
  assert.equal(projects.NEW.settings.scene_image_model,'moss');
  assert.equal(h.messages.filter(row=>row[1]==='err').length,0,JSON.stringify(h.messages));
  console.log('Main image settings whole-page UI passed: independent character/scene models, quality autosave, ordered switches, reload, normal save and old project isolation.');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
